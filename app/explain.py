"""Canonical scoring explanations (v1.5.0).

The "Why" column must be generated by the app, in one standard format, from the
scorer's own breakdown -- never assembled ad hoc in a template or written by
hand. This module is the single renderer for that column.

Format: every line is `<label>: <detail>  <points>` with points omitted when a
rule contributed nothing. Ordering is deterministic: highest contribution first,
then rule id, so the same film always renders identically.
"""
from __future__ import annotations

from typing import Any

# Stable, human labels per rule kind. One label per kind keeps the column
# uniform instead of mixing "genre", "Letterboxd rating" and "year".
RULE_LABELS = {
    "genre": "Genre",
    "country": "Country",
    "language": "Language",
    "year": "Year",
    "decade": "Decade",
    "rating": "IMDb rating",
    "letterboxd_rating": "Letterboxd rating",
    "popularity": "Popularity",
    "runtime": "Runtime",
    "source_position": "Watchlist position",
    "pace": "Frequency limit",
    "capacity": "Library capacity",
    "min_free_gb": "Minimum free disk",
    "max_free_gb": "Maximum free disk",
    "ignored": "Skipped",
    "not_released": "Digital release",
    "radarr_exists": "Already in Radarr",
    "storage_guard": "Storage guard",
}


def rule_label(kind: str | None) -> str:
    """Human label for a rule kind, never a raw internal id."""
    if not kind:
        return "Rule"
    return RULE_LABELS.get(kind, str(kind).replace("_", " ").capitalize())


def _fmt_points(points: Any) -> str:
    try:
        v = float(points)
    except (TypeError, ValueError):
        return ""
    if v == 0:
        return ""
    sign = "+" if v > 0 else "-"
    if float(v).is_integer():
        return f"{sign}{int(abs(v))}"
    return f"{sign}{abs(v):g}"


def explain(candidate: dict[str, Any]) -> list[dict[str, Any]]:
    """Build the standard Why-column lines for one candidate.

    Returns a list of ``{label, detail, points, kind, rule_id}`` dicts, already
    sorted. Sources, in priority order:
      1. matched scoring rules, highest contribution first
      2. an explicit "no rules matched" line so the column is never blank

    Intake gates are deliberately excluded. Use app.explain.status_line() for
    why a film is currently on hold.
    """
    breakdown = candidate.get("breakdown") or {}
    matched = breakdown.get("matched") or []

    lines: list[dict[str, Any]] = []
    for m in matched:
        kind = m.get("kind") or "rule"
        lines.append({
            "kind": kind,
            "rule_id": m.get("rule_id"),
            "label": rule_label(kind),
            # The scorer already produced the detail text; normalise spacing so
            # the column is uniform no matter which evaluator wrote it.
            "detail": " ".join(str(m.get("why") or "").split()),
            "points": _fmt_points(m.get("points")),
        })

    lines.sort(key=lambda x: (-abs(float(x["points"]) or 0), str(x["rule_id"])))

    # The Why column explains SCORING only. Intake gates (Pace, already in
    # Radarr, not yet released) are shown in the Status column instead -- showing
    # "Pace limit" here read as though the film had scored zero when it had not.
    if not lines:
        lines.append({
            "kind": "none",
            "rule_id": None,
            "label": "No rules matched",
            "detail": "this film does not match any rule on this watchlist",
            "points": "",
        })

    return lines


def summary(candidate: dict[str, Any]) -> str:
    """One-line, plain-text version -- used for the tooltip and exports."""
    parts = []
    for line in explain(candidate):
        pts = f" ({line['points']})" if line["points"] else ""
        parts.append(f"{line['label']}: {line['detail']}{pts}")
    return " | ".join(parts)


def status_line(candidate: dict[str, Any]) -> str:
    """One line describing why a film is on hold, or "" when it is ready.

    This is the counterpart to explain(): scoring reasons live in the Why column,
    intake gates live here so the two are never conflated.
    """
    breakdown = candidate.get("breakdown") or {}
    rejected = breakdown.get("rejected_by") or {}
    reason = candidate.get("blocked_reason") or rejected.get("reason")
    kind = candidate.get("blocked_by") or (rejected.get("rule") or {}).get("kind")
    if not reason:
        return ""
    return f"{rule_label(kind)}: {' '.join(str(reason).split())}"
